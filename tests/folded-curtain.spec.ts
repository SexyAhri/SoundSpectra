import { expect, test, type Page } from '@playwright/test'

const seek = async (page: Page,time: number) => {
  await page.evaluate(time=>window.foldStudy!.clock.seek(time),time)
  await page.waitForFunction(time=>window.foldStudy!.diagnostics.time===time+window.foldStudy!.clock.offset,time)
}
test.beforeEach(async ({page})=>{
  await page.goto('/experiments/folded-curtain.html')
  await page.waitForFunction(()=>window.foldStudy?.diagnostics.frames!>0)
})
test('bidirectional seek reconstructs the actual frame; pause is idle',async({page})=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
  await seek(page,6150)
  const before=await page.locator('canvas').screenshot()
  const pose=await page.evaluate(()=>window.foldStudy!.diagnostics.panels)
  await seek(page,20400);await seek(page,300);await seek(page,6150)
  expect(await page.evaluate(()=>window.foldStudy!.diagnostics.panels)).toEqual(pose)
  const after = await page.locator('canvas').screenshot()
  if (!after.equals(before)) {
    await test.info().attach('seek-before', { body: before, contentType: 'image/png' })
    await test.info().attach('seek-after', { body: after, contentType: 'image/png' })
  }
  expect(after.equals(before), 'seeking back must reproduce the same image').toBe(true)
  await page.waitForTimeout(100)
  const frames=await page.evaluate(()=>window.foldStudy!.diagnostics.frames)
  await page.waitForTimeout(450)
  expect(await page.evaluate(()=>window.foldStudy!.diagnostics.frames)).toBe(frames)
  await page.getByRole('button',{name:'播放',exact:true}).click()
  await page.waitForTimeout(180)
  await page.getByRole('button',{name:'暂停',exact:true}).click()
  expect(await page.evaluate(()=>window.foldStudy!.clock.read())).toBeGreaterThan(6150)
  expect(errors).toEqual([])
})
test('word boundaries, true sentence-only data, offset and reading stability',async({page})=>{
  await seek(page,3099)
  expect(await page.evaluate(()=>window.foldStudy!.diagnostics.highlighted[0])).toEqual([1,0,0,0])
  const stable=await page.evaluate(()=>window.foldStudy!.diagnostics.panels)
  await seek(page,3100)
  expect(await page.evaluate(()=>window.foldStudy!.diagnostics.highlighted[0])).toEqual([1,1,0,0])
  expect(await page.evaluate(()=>window.foldStudy!.diagnostics.panels)).toEqual(stable)
  await page.getByLabel('时间版本').selectOption('lines')
  await expect.poll(()=>page.evaluate(()=>window.foldStudy!.diagnostics.highlighted[0])).toEqual([1,1,1,1])
  await page.getByLabel('歌词偏移').fill('500')
  await expect.poll(()=>page.evaluate(()=>window.foldStudy!.diagnostics.time)).toBe(3600)
  await page.getByRole('button',{name:'重置样片'}).click()
  await expect.poll(()=>page.evaluate(()=>window.foldStudy!.diagnostics.time)).toBe(500)
  await expect(page.getByLabel('减少动态')).toHaveCount(0)
  await page.emulateMedia({reducedMotion:'reduce'})
  await seek(page,16000)
  const panels = await page.evaluate(()=>window.foldStudy!.diagnostics.panels)
  await page.emulateMedia({reducedMotion:'no-preference'})
  await seek(page,16000)
  expect(await page.evaluate(()=>window.foldStudy!.diagnostics.panels)).toEqual(panels)
})
test('all lines readable at onset, quick transitions clear previous line, resize and hidden stop drawing',async({page})=>{
  for(const time of [1800,6500,11400,16200,17600,24500]) {
    await seek(page,time)
    const d=await page.evaluate(()=>window.foldStudy!.diagnostics)
    expect(d.poses.some(p=>p[0]===1 && p[1]===0)).toBe(true)
    expect(d.panels.some(p=>p[4]===0 && p[5]===1)).toBe(true)
  }
  await seek(page,6500)
  expect(await page.evaluate(()=>window.foldStudy!.diagnostics.visible)).toEqual([1])
  await page.setViewportSize({width:430,height:900});await seek(page,20500)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(430)
  await page.evaluate(()=>{window.foldStudy!.clock.play(true);Object.defineProperty(document,'hidden',{configurable:true,get:()=>true});document.dispatchEvent(new Event('visibilitychange'))})
  await page.waitForTimeout(100)
  const frames=await page.evaluate(()=>window.foldStudy!.diagnostics.frames)
  await page.waitForTimeout(250)
  expect(await page.evaluate(()=>window.foldStudy!.diagnostics.frames)).toBe(frames)
  await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,get:()=>false});document.dispatchEvent(new Event('visibilitychange'))})
  await expect.poll(()=>page.evaluate(()=>window.foldStudy!.diagnostics.frames)).toBeGreaterThan(frames)
})
test('replacement document drops old geometry and stale lyric poses',async({page})=>{
  await seek(page,20500)
  await page.evaluate(()=>window.foldStudy!.replaceScore([{start:20000,end:24000,phrases:[{words:[{text:'新的片段',start:20500,end:23000}]}]}]))
  await expect.poll(()=>page.evaluate(()=>window.foldStudy!.diagnostics.resources)).toBe(1)
  await expect.poll(()=>page.evaluate(()=>window.foldStudy!.diagnostics.panels.length)).toBe(1)
  expect(await page.evaluate(()=>window.foldStudy!.diagnostics.visible)).toEqual([0])
  await seek(page,500)
  expect(await page.evaluate(()=>window.foldStudy!.diagnostics.visible)).toEqual([])
  await page.evaluate(()=>window.foldStudy!.replaceScore(null))
  await expect.poll(()=>page.evaluate(()=>window.foldStudy!.diagnostics.resources)).toBe(25)
})
